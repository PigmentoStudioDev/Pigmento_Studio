/**
 * Los iconos del sitio, por NOMBRE.
 *
 * El nombre y no el SVG es lo que hace que quien lo use siga teniendo props
 * serializables: una red social que llega de una global de Payload es la cadena
 * "instagram", no un nodo de React. Pasar el dibujo como children obligaria al
 * adaptador del CMS a componer en vez de mapear, y ahi se rompe la equivalencia
 * bloque-organismo que sostiene todo el modelo.
 *
 * Los trazados van en `currentcolor`, nunca con el color con el que vinieron. Un
 * `fill="black"` sobrevive al modo oscuro dibujando un icono negro sobre fondo
 * negro — sin error y sin que nada lo avise.
 *
 * Decorativo por defecto: `aria-hidden`. Un icono acompana a un nombre accesible
 * que pone quien lo envuelve — el enlace, el boton — y nombrarse a si mismo produce
 * dos nombres para un solo control.
 */
export type IconName =
  | "instagram"
  | "facebook"
  | "behance"
  | "sun"
  | "moon"
  | "arrow"
  | "chevron";

/**
 * Un icono es una LISTA de trazados: los de marca no son una sola figura. El de
 * Instagram son tres — marco, lente y punto — y aplanarlos a uno los fundiria.
 *
 * Y hay DOS familias de dibujo. Los logotipos son siluetas rellenas; los de
 * interfaz son lineas. Pintar una linea con `fill` la convierte en una mancha, asi
 * que cada icono declara como se pinta en vez de que lo adivine quien lo use.
 */
interface IconDefinition {
  readonly paths: readonly string[];
  /** Dibujado a linea y no a relleno. El grosor va con el, no en quien lo llama. */
  readonly stroke?: boolean;
  /**
   * Lienzo propio, cuando el dibujo no cabe en la reticula de 24.
   *
   * Se declara en vez de reescalar los trazados: reescribir a mano las coordenadas
   * de un trazado para meterlo en otro viewBox es aritmetica sin verificacion — un
   * digito mal y el dibujo sale deformado sin que nada falle. El SVG ya sabe
   * encajar su lienzo en la caja que le den.
   */
  readonly viewBox?: string;
}

